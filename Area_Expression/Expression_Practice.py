
#Write a program for finding Area of Rectangular

length = int(input("Enter length value: "))
breadth = int(input("Enter breadth value: "))

area = length * breadth

print("Area of Rectangular is: ", area)

#using float conversion in the input

length1 = float(input("Enter float value length: "))
breadth1 = float(input("Enter float value breadth: "))

